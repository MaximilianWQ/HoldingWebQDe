"use client";

import { useEffect } from "react";
import type { Locale } from "@/lib/locale";

/**
 * Держит `<html lang>` в согласии с языком открытой страницы.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ КОМПОНЕНТ. Атрибут ставит корневой `layout.tsx`, но
 * layout при переходах внутри приложения НЕ перерисовывается — это его
 * смысл. Поэтому при мягком переходе с `/pricing` на `/en/pricing`
 * текст становился английским, а `lang` оставался «ru» (замер
 * 21.09.2026). Для глаза незаметно, а экранный диктор начинает читать
 * английский текст русскими правилами — и его не разобрать.
 *
 * Значение приходит пропсом от серверной оболочки, то есть из того же
 * источника, что и весь текст страницы. Своей логики определения
 * языка здесь нет и быть не должно: второй источник правды о языке —
 * это расхождение, которое обнаружится через месяц.
 */
export default function HtmlLang({ locale }: { locale: Locale }) {
  useEffect(() => {
    if (document.documentElement.lang !== locale) {
      document.documentElement.lang = locale;
    }
  }, [locale]);
  return null;
}
