/**
 * Фигуры первого экрана вакансий (владелец, 19.09.2026: прислал
 * разворот ecom.tech — «сделай похожее, технологичным»).
 *
 * Люди набраны блоками: голова, корпус, рука, две ноги — прямоугольники
 * со скруглением, ни одной кривой. Это то же правило, что у иконок
 * корпуса: рисуем сами, штрихом и сеткой, без стоковых иллюстраций и
 * без сторонних наборов.
 *
 * Идут они не «в никуда»: шаг каждой фигуры сдвинут по фазе, и три
 * силуэта читаются как один человек в движении — разложенный на кадры,
 * как в раскадровке. Отсюда и разная насыщенность: первый кадр
 * бледный, последний в полную силу.
 *
 * Движение объявлено в careers.css и живёт только при
 * `prefers-reduced-motion: no-preference`; в покое фигуры стоят в
 * середине шага — позе, которая читается как ходьба и без анимации.
 *
 * Разметка декоративная: рядом стоит заголовок, который говорит то же
 * самое словами, поэтому для чтеца экрана фигур нет.
 */
const FIGURES = [0, 1, 2];

export default function TeamFigures() {
  return (
    <div className="tc-figs" aria-hidden>
      <svg viewBox="0 0 300 200" role="presentation" focusable="false">
        {FIGURES.map((i) => (
          <g key={i} className="tc-fig" style={{ ["--i" as string]: i }} transform={`translate(${14 + i * 100} 16)`}>
            {/* голова */}
            <rect className="tc-fig-head" x="26" y="0" width="20" height="20" rx="5" />
            {/* корпус */}
            <rect x="24" y="26" width="24" height="48" rx="7" />
            {/* рука */}
            <rect className="tc-fig-arm" x="46" y="30" width="11" height="34" rx="5" />
            {/* ноги */}
            <rect className="tc-fig-leg tc-fig-leg-a" x="24" y="76" width="11" height="46" rx="5" />
            <rect className="tc-fig-leg tc-fig-leg-b" x="37" y="76" width="11" height="46" rx="5" />
            {/* опора: короткий штрих под фигурой, чтобы она не висела */}
            <rect className="tc-fig-floor" x="14" y="128" width="44" height="3" rx="1.5" />
          </g>
        ))}
      </svg>
    </div>
  );
}
