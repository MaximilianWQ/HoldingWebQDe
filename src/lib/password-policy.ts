/**
 * Требования к паролю — одно место на весь сайт.
 *
 * ПОЧЕМУ ФАЙЛ ПОЯВИЛСЯ (аудит безопасности 19.09.2026). Правил было
 * два. Смена пароля в кабинете требовала восьми знаков, букв и цифр и
 * отсекала явный мусор. Восстановление по «Забыли пароль?» — шести
 * знаков и ничего больше. То есть более слабое правило стояло ровно на
 * том пути, до которого доберётся посторонний, получивший доступ к
 * почте: он назначил бы `123456` и закрепился в аккаунте.
 *
 * Слабый пароль опаснее там, где к нему добавляется вход по паролю без
 * письма. Поэтому правило одно и жёсткое.
 */
export const PASSWORD_MIN = 8;
export const PASSWORD_MAX = 128;

/** Самые частые пароли — их подбирают первыми. */
const WEAK = [
  "12345678", "password", "qwerty12", "00000000", "11111111",
  "123456789", "qwertyui", "1qaz2wsx", "password1", "iloveyou",
  "11223344", "987654321", "qwerty123", "1q2w3e4r",
];

/** null — пароль годится; строка — что показать человеку. */
export function passwordProblem(password: unknown): string | null {
  if (typeof password !== "string" || password.length < PASSWORD_MIN) {
    return `Пароль должен содержать минимум ${PASSWORD_MIN} символов`;
  }
  if (password.length > PASSWORD_MAX) {
    return "Пароль слишком длинный";
  }
  if (!/[a-zA-Zа-яА-ЯёЁ]/.test(password) || !/[0-9]/.test(password)) {
    return "Пароль должен содержать буквы и цифры";
  }
  if (WEAK.includes(password.toLowerCase())) {
    return "Такой пароль подбирают первым. Придумайте другой";
  }
  return null;
}
