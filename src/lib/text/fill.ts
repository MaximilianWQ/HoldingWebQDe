/**
 * Подстановка в строку: `fill("Привет, {name}", { name: "Иван" })`.
 *
 * ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ В `index.ts` — и это не вкусовщина, а замер
 * (21.09.2026). `index.ts` статически импортирует ОБА словаря; пятнадцать
 * клиентских компонентов брали оттуда одну эту функцию — и вместе с ней
 * в браузер уезжали русский и английский словари целиком. В собранном
 * приложении это был чанк 240 КБ в первой загрузке двенадцати
 * маршрутов.
 *
 * То есть нарушалось правило, записанное в CLAUDE.md («клиентские
 * компоненты словарь не импортируют»): формально словарь никто не
 * импортировал, а фактически он приезжал через общий файл.
 *
 * Здесь нет ни одного импорта, и это главное свойство файла. Класть
 * сюда что-либо, зависящее от словарей, нельзя — иначе 240 КБ
 * вернутся, и никто этого не заметит.
 */
export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
